#!/usr/bin/env python3
"""Render spec/<version>/README.md from spec/<version>/tables.yaml (design plan §3.1).

Usage:
    scripts/render-spec-readme.py [--spec-version 1.0]          # write README.md
    scripts/render-spec-readme.py [--spec-version 1.0] --check  # exit 1 if README.md is stale

The output is deterministic (no dates). It carries the YAML's leading comment block and every `# unconfirmed:`
comment, so the README shows what the capture still has to confirm.
"""

from __future__ import annotations

import argparse
import re
import sys

import duckdb
import yaml

from clinvar_gkm_parquet.spec import parse_spec, spec_dir

_TABLE = re.compile(r"^  - name: (\S+)\s*$")
_COLUMN = re.compile(r"^      - name: (\S+)\s*$")


def _comments(text: str) -> tuple[list[str], dict[tuple[str, str], str]]:
    """(header comment lines, {(table, column): unconfirmed note}) from the YAML text."""
    header: list[str] = []
    lines = text.splitlines()
    for line in lines:
        if not line.startswith("#"):
            break
        header.append(line[1:].removeprefix(" "))
    notes: dict[tuple[str, str], str] = {}
    table = None
    pending: list[str] = []
    for line in lines:
        s = line.strip()
        if m := _TABLE.match(line):
            table, pending = m.group(1), []
        elif m := _COLUMN.match(line):
            text_ = " ".join(pending)
            if "unconfirmed:" in text_:
                notes[(table, m.group(1))] = text_.split("unconfirmed:", 1)[1].strip()
            pending = []
        elif s.startswith("#"):
            pending.append(s[1:].strip())
        elif s:
            pending = []
    return header, notes


def _short(type_str: str) -> str:
    """STRUCT(a X, b Y)[] -> STRUCT(a, b)[], the compact form of ClinVar-GKM's column reference."""
    t = duckdb.sqltype(type_str)
    if t.id == "list":
        return _short(str(t.children[0][1])) + "[]"
    if t.id == "struct":
        return "STRUCT(" + ", ".join(f for f, _ in t.children) + ")"
    return type_str


def _cell(s: str | None) -> str:
    """Text for a Markdown table cell: | escaped, and < > as entities so `<id>` isn't read as an HTML tag."""
    return "" if s is None else str(s).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def render(version: str) -> str:
    path = spec_dir(version) / "tables.yaml"
    text = path.read_text(encoding="utf-8")
    spec = parse_spec(yaml.safe_load(text), where=str(path))
    header, notes = _comments(text)
    out = [
        f"# Table spec {spec.spec_version}",
        "",
        "<!-- Generated by scripts/render-spec-readme.py from tables.yaml. Do not edit by hand. -->",
        "",
        f"- **Status:** {spec.status}",
        f"- **Bundle schema versions:** {', '.join(spec.bundle_schema_versions)}",
        f"- **Writer:** {', '.join(f'{k} {v}' for k, v in spec.writer.items())}",
        f"- **Tables:** {len(spec.tables)}",
        "",
        "## Notes",
        "",
        "```text",
        *header,
        "```",
        "",
        "## Sources",
        "",
        *[f"- {s}" for s in spec.sources],
        "",
        "## Tables",
        "",
        "| Table | Sections | Sort key | Columns | Description |",
        "| --- | --- | --- | ---: | --- |",
        *[
            f"| [`{t.name}`](#{t.name.lower()}) | {', '.join(t.sections)} | `{t.sort_key}` | {len(t.columns)} "
            f"| {_cell(t.description)} |"
            for t in spec.tables
        ],
        "",
    ]
    for t in spec.tables:
        out += [
            f"### {t.name}",
            "",
            _cell(t.description),
            "",
            f"`{t.file_name}` · sections: {', '.join(t.sections)} · sort key: `{t.sort_key}`"
            + (f" · row filter: {t.row_filter}" if t.row_filter else "")
            + (
                " · known fields: a top-level record field no column reads stops the build"
                if t.known_fields
                else ""
            ),
            "",
            "| # | Column | Type | Nulls | Derivation | Path | Transform | Description |",
            "| ---: | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for i, c in enumerate(t.columns, 1):
            d = c.derivation
            desc = _cell(c.description)
            if (t.name, c.name) in notes:
                desc += f" **Unconfirmed:** {_cell(notes[(t.name, c.name)])}"
            transform = _cell(d.transform)
            if d.pointers:
                transform += f"{'; ' if transform else ''}pointers: {', '.join(f'`{x}`' for x in d.pointers)}"
            out.append(
                f"| {i} | `{c.name}` | `{_short(c.type)}` | {c.nulls} | {d.kind} | "
                f"{'`' + d.path + '`' if d.path else ''} | {transform} | {desc} |"
            )
        nested = [c for c in t.columns if c.type != _short(c.type)]
        if nested:
            out += ["", "Full nested types:", "", "```text"]
            out += [f"{c.name}  {c.type}" for c in nested]
            out += ["```"]
        for col, mapping in t.extension_slots.items():
            out += ["", f"Extension slots of `{col}`:", "", "| Extension name | Slot |", "| --- | --- |"]
            out += [f"| `{n}` | `{s}` |" for n, s in mapping.items()]
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec-version", default="1.0")
    ap.add_argument("--check", action="store_true", help="exit 1 if README.md is not up to date")
    args = ap.parse_args(argv)
    readme = spec_dir(args.spec_version) / "README.md"
    text = render(args.spec_version)
    if args.check:
        current = readme.read_text(encoding="utf-8") if readme.exists() else ""
        if current != text:
            print(f"{readme} is stale: run scripts/render-spec-readme.py --spec-version {args.spec_version}")
            return 1
        return 0
    readme.write_text(text, encoding="utf-8")
    print(f"wrote {readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
