#!/usr/bin/env python3
"""Write spec/baseline/<version>/tables.yaml, the built-in baseline spec (ADR 0003): one table per bundle section.

Usage:
    scripts/make-baseline-spec.py           # write the file
    scripts/make-baseline-spec.py --check   # exit 1 if the file differs from what this script writes

The YAML file is what the tool loads; this script only keeps its 20 near-identical tables consistent. The sections
come from compat.SCHEMA_SECTIONS for the schema_versions below. A released spec version is never edited: a
change here that alters the output needs a new version (.claude/rules/table-spec.md).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from clinvar_gkm_parquet.baseline import REFS_TYPE
from clinvar_gkm_parquet.compat import SCHEMA_SECTIONS

VERSION = "1.0"
SCHEMA_VERSIONS = ["1.1.0"]
OUT = Path(__file__).resolve().parents[1] / "spec" / "baseline" / VERSION / "tables.yaml"

HEADER = """\
# Table spec baseline 1.0: one table per section of the 1.1.0 bundle, each `id, refs, data` (ADR 0003).
# Generated by scripts/make-baseline-spec.py; edit the script, not this file.
# Format: src/clinvar_gkm_parquet/spec.py. Rules: .claude/rules/table-spec.md. Renderer: baseline.py.
#
# The default spec: a build with no --spec writes these tables. Every value is the bundle's own: the key, the
# pointers the record holds (with where it holds them), and the record byte for byte. Nothing is typed beyond
# that, so the tables don't change when a record's fields do.
"""

REFS_TRANSFORM = (
    "every JSON string value in the record whose text starts '#/', in document order. A string that starts '#/' "
    "but does not match ^#/[^/]+/. stops the build. path = the string's position from the record root: object "
    "keys joined by '.', each array position written '[]', and a key that is empty or holds . [ ] \" or \\ "
    "written as a JSON string. section = the text between the first two '/'; id = the text after the second "
    "'/'. [] when the record holds no pointer."
)

REFS_DESCRIPTION = (
    "Every #/<section>/<id> pointer in the record: where it is (path), and the section and id it names."
)


def q(s: str) -> str:
    """A YAML scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


def render() -> str:
    sections = SCHEMA_SECTIONS[SCHEMA_VERSIONS[0]]
    for v in SCHEMA_VERSIONS[1:]:
        if SCHEMA_SECTIONS[v] != sections:
            raise SystemExit(f"schema {v} has other sections than {SCHEMA_VERSIONS[0]}")
    lines = [
        HEADER.rstrip("\n"),
        "name: baseline",
        f"spec_version: {q(VERSION)}",
        "status: draft",
        f"bundle_schema_versions: {json.dumps(SCHEMA_VERSIONS)}",
        "sources:",
        "  - "
        + q(
            "ClinVar-GKM schema/clinvar-gkm/clinvar-gkm-bundle.schema.json @ origin/1.0 "
            "25344ba6edb639bacbdd8af38bd90a2e6b9f4240 (the 20 sections of 1.1.0)"
        ),
        "  - " + q("ClinVar-GKM src/scripts/assemble-gkm-dicts.py @ origin/1.0 25344ba (one record per line)"),
        "writer:",
        "  compression: snappy",
        "  row_group_size: 122880",
        "tables:",
    ]
    for s in sections:
        lines += [
            f"  - name: {s}",
            f"    sections: [{s}]",
            "    row_filter: null",
            "    sort_key: id",
            f"    description: {q(f'Every record of the bundle section {s}, with the pointers it holds.')}",
            "    columns:",
            "      - name: id",
            "        type: VARCHAR",
            "        nulls: never",
            "        derivation: {kind: key, path: null, transform: null}",
            f"        description: {q(f'The bundle key of the record in section {s}.')}",
            "      - name: refs",
            f"        type: {q(REFS_TYPE)}",
            "        nulls: empty-list",
            f"        derivation: {{kind: refs, path: $, transform: {q(REFS_TRANSFORM)}}}",
            f"        description: {q(REFS_DESCRIPTION)}",
            "      - name: data",
            "        type: JSON",
            "        nulls: never",
            "        derivation: {kind: record, path: null, transform: null}",
            "        description: " + q("The bundle record, byte for byte as on its bundle line, typed JSON."),
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = p.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run scripts/make-baseline-spec.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
